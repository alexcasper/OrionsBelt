"""Benchmark runner CLI — context sweep, warmup, repeats, percentiles.

Implements the measurement protocol from ``docs/METRICS.md`` and emits
schema-conformant CSV via ``bench/schema.py`` (bead ``ob-ljh``).

**Design: pluggable backend.** The harness defines *how* to measure
(warmup → timed repeats → per-repeat rows), not *what* to run.  An
``InferenceBackend`` protocol is injected so the same harness works on
NPU, GPU, CPU, llama.cpp, or transformers — each device plugs in its own
backend.  The harness's job is the measurement contract; the backend's
job is the actual inference.

Usage::

    # full sweep with a real backend
    python -m bench.harness \\
        --backend my_backend \\
        --model-checkpoint Qwen/Qwen3.5-4B \\
        --context-lengths 4096,32768,131072,262144 \\
        --warmups 3 --repeats 5 \\
        --device generic_aarch64 \\
        --engine-gdn cpu --engine-full-attention cpu \\
        --quantization fp16 \\
        --output results/raw/my_run.csv

    # smoke test with a synthetic backend (no model needed)
    python -m bench.harness --backend synthetic --repeats 3 --context-lengths 4096 \\
        --model-checkpoint test --device x86_reference \\
        --engine-gdn cpu --engine-full-attention cpu \\
        --quantization fp16 --output /tmp/smoke.csv
"""

